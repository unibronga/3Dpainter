/**
 * Индикатор занятости.
 *
 * Чтение модели, экспорт и пересборка текстур считаются в основном потоке и
 * на крупной сцене занимают заметное время. Без знака человек не понимает,
 * идёт работа или программа его не услышала, и жмёт второй раз.
 *
 * 🔴 Показать мало — надо успеть нарисовать. Тяжёлая работа блокирует поток,
 * и если запустить её сразу после `classList.add`, кадр не выйдет на экран:
 * человек увидит индикатор уже после того, как всё закончилось. Поэтому
 * между показом и работой уступается два кадра.
 *
 * 🔴 Показывается сразу, без выжидания. Ждать «вдруг управится быстро» здесь
 * нельзя: тяжёлая работа синхронная, она занимает поток целиком, и таймер
 * отложенного показа сработал бы только после её конца — то есть индикатора
 * не было бы видно вовсе. Зато показавшись, он держится МИНИМУМ, чтобы на
 * быстрой машине не моргнуть и исчезнуть.
 */

import { t, onLangChange } from './i18n.js';

const МИНИМУМ = 260;    // мс: показался — держись, чтобы не мигнуть

const эл = (тег, класс) => {
  const у = document.createElement(тег);
  if (класс) у.className = класс;
  return у;
};

let слой = null;
let подпись = null;
let ключПодписи = '';
let глубина = 0;        // вложенные операции: индикатор один на всех
let показаноВ = 0;

function построить() {
  if (слой) return;

  слой = эл('div', 'busy-back');
  const карточка = эл('div', 'busy');

  // Кольцо рисуем SVG: одна дуга крутится, вторая стоит подложкой.
  const кольцо = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  кольцо.setAttribute('viewBox', '0 0 40 40');
  кольцо.setAttribute('class', 'busy-ring');
  кольцо.innerHTML =
    '<circle class="busy-track" cx="20" cy="20" r="16" fill="none" stroke-width="3.5"/>'
    + '<circle class="busy-arc" cx="20" cy="20" r="16" fill="none" stroke-width="3.5"'
    + ' stroke-linecap="round" stroke-dasharray="26 74"/>';

  подпись = эл('div', 'busy-text');
  карточка.append(кольцо, подпись);
  слой.appendChild(карточка);
  document.body.appendChild(слой);

  onLangChange(() => { if (ключПодписи) подпись.textContent = t(ключПодписи); });
}

/**
 * Уступить браузеру кадр — иначе показанный индикатор не успеет нарисоваться.
 *
 * 🔴 Свёрнутое или скрытое окно кадров не рисует вовсе: `requestAnimationFrame`
 * там не вызывается, и ожидание кадра не кончилось бы никогда — открытие
 * файла повисло бы намертво. Поэтому ждём кадр ИЛИ таймер, что раньше.
 */
const кадр = () => new Promise((ок) => {
  let сделано = false;
  const готово = () => { if (!сделано) { сделано = true; ок(); } };
  requestAnimationFrame(() => requestAnimationFrame(готово));
  setTimeout(готово, 50);
});

function показать(ключ, ...значения) {
  построить();
  ключПодписи = ключ;
  подпись.textContent = t(ключ, ...значения);

  if (глубина === 0) {
    показаноВ = performance.now();
    слой.classList.add('on');
  }
  глубина += 1;
}

async function спрятать() {
  глубина = Math.max(0, глубина - 1);
  if (глубина > 0) return;

  if (!слой?.classList.contains('on')) return;

  const прошло = performance.now() - показаноВ;
  if (прошло < МИНИМУМ) await new Promise((ок) => setTimeout(ок, МИНИМУМ - прошло));
  слой.classList.remove('on');
}

/**
 * Выполнить работу под индикатором.
 * @param {string} ключ ключ надписи, например 'busy.open'
 * @param {() => any} дело сама работа; результат возвращается наружу
 * @param {...any} значения подстановки в надпись
 */
export async function withBusy(ключ, дело, ...значения) {
  показать(ключ, ...значения);
  try {
    await кадр();          // даём индикатору попасть на экран
    return await дело();
  } finally {
    await спрятать();
  }
}

/** Сменить надпись, не закрывая индикатор: у длинной работы бывают этапы. */
export function busyNote(ключ, ...значения) {
  if (!подпись) return;
  ключПодписи = ключ;
  подпись.textContent = t(ключ, ...значения);
}
